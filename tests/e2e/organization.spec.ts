import { test, expect, signIn, createCourse, headers, capture } from './fixtures'

test('note context menu, nested categories, course icon and collapsed settings survive navigation', async ({ page, accounts }) => {
  await page.goto('/login')
  const logo = await page.locator('link[rel=icon]').getAttribute('href')
  expect(logo).toBe('/favicon.svg')
  await expect(page.locator('.session-panel .brand img')).toHaveAttribute('src', logo!)
  await signIn(page, accounts.author)
  await expect(page.locator('.navigator-heading .brand img')).toHaveAttribute('src', logo!)
  const courseId = await createCourse(page.request, 'Математический анализ')
  const title = 'Производная композиции'
  const note = await (await page.request.post('/api/notes', { headers, data: { courseId, title } })).json()
  await page.goto('/courses/' + courseId)
  await page.getByRole('button', { name: 'Сменить значок' }).click()
  await page.getByRole('button', { name: 'Математика', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  for (const name of ['Анализ','Производные']) {
    await page.getByRole('main').getByRole('button', { name: 'Создать подкатегорию', exact: true }).click()
    await page.getByLabel('Название категории').fill(name)
    await page.getByRole('dialog').getByRole('button', { name: 'Создать подкатегорию', exact: true }).click()
    await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
    await page.reload()
    await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  }
  await page.getByRole('main').getByRole('button',{name:'Добавить заметку',exact:true}).click()
  await expect(page.getByRole('dialog').getByLabel('Категория')).toHaveValue(courseId + '/Анализ/Производные')
  await page.getByRole('button',{name:'Создать заметку',exact:true}).click()
  await expect(page.locator('.note-editor')).toBeVisible()
  const details = (await (await page.request.get('/api/state')).json()).notes.find((n: {title: string}) => n.title === 'Без названия')
  expect(details.category).toBe('Анализ/Производные')
  await page.goto('/courses/' + courseId)
  await page.locator('.note-list-row').filter({ hasText: title }).click({ button: 'right' })
  const actions = page.locator('.action-menu-popover:popover-open')
  await expect(actions).toBeVisible()
  const menuInset = await actions.evaluate(panel => {
    const bounds = panel.getBoundingClientRect()
    return Math.min(...Array.from(panel.children, item => {
      const range = document.createRange()
      range.selectNodeContents(item)
      return bounds.right - range.getBoundingClientRect().right
    }))
  })
  expect(menuInset).toBeGreaterThanOrEqual(14)
  await capture(page, 'note-menu-1440')
  await page.getByRole('button', { name: 'Переместить в категорию' }).click()
  await page.getByLabel('Куда переместить').selectOption('Анализ/Производные')
  await page.getByRole('dialog').getByRole('button', { name: 'Сохранить' }).click()
  await page.goto('/notes/' + note.id)
  await expect(page.locator('.folder-branch .folder-branch a.active')).toHaveText(title)
  const treeNote = page.locator('.folder-branch a.active')
  await treeNote.hover()
  const row = treeNote.locator('..')
  expect(await row.evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe('rgba(0, 0, 0, 0)')
  await treeNote.click({ button: 'right' })
  const menuItems = page.locator('.action-menu-popover:popover-open > .button')
  const leftEdges = await menuItems.evaluateAll(items => items.map(el => el.getBoundingClientRect().left + parseFloat(getComputedStyle(el).paddingLeft)))
  expect(Math.max(...leftEdges) - Math.min(...leftEdges)).toBeLessThan(1)
  await capture(page, 'tree-note-menu-1440')
  await page.keyboard.press('Escape')
  await treeNote.focus()
  await page.keyboard.press('Shift+F10')
  await expect(page.getByRole('link', { name: 'Скачать Markdown', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('link', { name: 'Скачать Markdown', exact: true })).toBeHidden()
  await page.getByRole('button', { name: 'Скрыть проводник' }).click()
  await page.locator('.rail-settings').click()
  await expect(page.getByRole('heading', { name: 'Настройки', exact: true })).toBeVisible()
  await page.goto('/')
  await page.getByRole('link',{name:'Все заметки',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Все заметки'})).toBeVisible()
  await expect(page.locator('.note-list-row').filter({ hasText: title })).toContainText('Анализ / Производные')
  await page.goBack()
  await expect(page.getByRole('heading',{name:'Категории',exact:true})).toBeVisible()
  const catalog = (await page.locator('.library-courses').boundingBox())!
  const recent = (await page.locator('.library-recent').boundingBox())!
  expect(recent.y).toBeGreaterThan(catalog.y + catalog.height)
  expect(Math.abs(recent.x - catalog.x)).toBeLessThan(1)
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 })
    const table = page.locator('.library-recent').getByRole('table')
    const header = table.getByRole('columnheader', { name: 'Изменено' }).locator('..')
    const row = table.getByRole('row').filter({ hasText: title })
    const [headBox, rowBox] = await Promise.all([header.boundingBox(), row.boundingBox()])
    expect(headBox!.x).toBeCloseTo(rowBox!.x, 0)
    expect(headBox!.width).toBeCloseTo(rowBox!.width, 0)
    await expect(header).toHaveCSS('border-bottom-width', '1px')
    await expect(header.getByRole('columnheader', { name: 'Изменено' })).toHaveCSS('border-bottom-width', '0px')
    await capture(page, 'categories-library-' + width)
  }
  const main = page.getByRole('main')
  const dialog = page.getByRole('dialog')
  await main.getByRole('button', {name:'Создать категорию',exact:true}).click()
  await dialog.getByLabel('Родительская категория').selectOption(courseId + '/Анализ/Производные')
  await dialog.getByLabel('Название категории').fill('Практика')
  await capture(page, 'choose-parent-390')
  await dialog.getByRole('button',{name:'Создать подкатегорию'}).click()
  await expect(main.getByRole('heading',{name:'Практика',exact:true})).toBeVisible()
  await main.getByLabel('Действия категории', {exact:true}).click()
  await page.getByRole('button',{name:'Переименовать',exact:true}).click()
  const renameField = dialog.getByLabel('Название категории')
  await expect(renameField).toHaveValue('Практика')
  await capture(page, 'category-rename-390')
  await renameField.fill('Задачи')
  await dialog.getByRole('button',{name:'Сохранить'}).click()
  await expect(main.getByRole('heading',{name:'Задачи',exact:true})).toBeVisible()
  await page.reload()
  await expect(main.getByRole('heading',{name:'Задачи',exact:true})).toBeVisible()
  await page.goto('/courses/' + courseId + '?' + new URLSearchParams({folder:'Анализ/Производные'}))
  await main.getByLabel('Действия категории', {exact:true}).click()
  await page.getByRole('button',{name:'Объединить с родителем'}).click()
  await dialog.getByRole('button',{name:'Объединить',exact:true}).click()
  await expect(main.getByRole('heading',{name:'Анализ',exact:true})).toBeVisible()
  await expect(main.getByRole('link',{name:'Задачи',exact:true})).toBeVisible()
  await expect(main.locator('.note-list-row').filter({hasText:title})).toBeVisible()
  await expect(main.locator('.breadcrumbs').getByRole('link',{name:'Математический анализ'})).toBeVisible()
  await expect(main.locator('.breadcrumbs [aria-current="page"]')).toHaveText('Анализ')
  await capture(page, 'category-children-390')
  await page.setViewportSize({width:1440,height:1000})
  await capture(page, 'category-children-1440')
  await page.goto('/notes/' + note.id)
  await expect(main.locator('.breadcrumbs')).toContainText('Анализ')
  await main.getByLabel('Действия заметки',{exact:true}).click()
  page.once('dialog', confirmation => confirmation.accept())
  await page.getByRole('button',{name:'Удалить',exact:true}).click()
  await expect(main.getByRole('heading',{name:'Анализ',exact:true})).toBeVisible()
  await expect(main.getByRole('link',{name:'Без названия',exact:false})).toBeVisible()
  await expect(main.locator('.note-list-row').filter({hasText:title})).toHaveCount(0)
})

test('editable image sizes, table command and compact drag feedback change the saved note', async ({ page, accounts }) => {
  await signIn(page, accounts.author)
  const courseId = await createCourse(page.request, 'Архитектура сети')
  const response = await page.request.post('/api/notes', { headers, data: { courseId, title: 'Устройство сети', markdown: '' } })
  const note = await response.json()
  const jpeg = await page.evaluate(async () => {
    const canvas = document.createElement('canvas')
    canvas.width = 600
    canvas.height = 180
    const ctx = canvas.getContext('2d')!
    const diagram = new Image()
    diagram.src = '/demo-replication.svg'
    await diagram.decode()
    ctx.drawImage(diagram, 0, 0, canvas.width, canvas.height)
    return canvas.toDataURL('image/jpeg').split(',')[1]
  })
  const uploadPath = '/api/notes/' + note.id + '/assets'
  const upload = await page.request.post(uploadPath, { headers, multipart: { file: { name: 'network.jpg', mimeType: 'image/jpeg', buffer: Buffer.from(jpeg, 'base64') } } })
  expect(upload.status()).toBe(201)
  const { url } = await upload.json()
  const markdown = [
    'Первый абзац', 'Второй абзац', 'Третий абзац', 'До ![Узлы](' + url + ' "Подпись в строке [width=50%]") после',
    '| Узел | Адрес |\n| --- | --- |\n| A | 100 |\n| B | 200 |',
    '![Схема сети](' + url + ' "Исходная подпись")',
  ].join('\n\n')
  expect((await page.request.patch('/api/notes/' + note.id, { headers, data: { title: note.title, markdown, revision: note.revision } })).status()).toBe(200)
  let unexpectedUploads = 0
  page.on('request', request => { if (new URL(request.url()).pathname === uploadPath && request.method() === 'POST') unexpectedUploads++ })
  await page.goto('/notes/' + note.id + '/edit')
  const editor = page.locator('.ProseMirror[aria-label="Текст заметки"]')
  const first = editor.locator(':scope > p').filter({ hasText: 'Первый абзац' })
  const third = editor.locator(':scope > p').filter({ hasText: 'Третий абзац' })
  await first.click()
  await expect(editor).toBeFocused()
  await expect(editor).toHaveCSS('outline-style', 'none')
  // Observe the real drag operation while allowing Chromium to perform its native drop.
  await page.evaluate(() => {
    document.addEventListener('dragover', event => {
      if (event.target instanceof Element && event.target.closest('.ProseMirror') && event.dataTransfer) document.body.dataset.dropEffect = event.dataTransfer.dropEffect
    })
    const original = DataTransfer.prototype.setDragImage
    DataTransfer.prototype.setDragImage = function(element, x, y) {
      if (element.classList.contains('block-drag-preview')) document.body.dataset.lastPreview = element.textContent || ''
      return original.call(this, element, x, y)
    }
  })
  await first.hover()
  const handle = page.locator('.milkdown-block-handle .operation-item').last()
  await expect(handle).toBeVisible()
  const bounds = await third.boundingBox()
  await handle.dragTo(third, { targetPosition: { x: 12, y: Math.floor(bounds!.height - 1) } })
  await expect(page.locator('body')).toHaveAttribute('data-last-preview', 'Первый абзац')
  await expect(editor.locator(':scope > p').first()).toHaveText('Второй абзац')
  await expect(page.locator('body')).toHaveAttribute('data-drop-effect', 'move')
  const rows = editor.locator('table.children tr')
  await rows.nth(1).locator('td').first().click()
  await page.getByRole('button', { name: 'Вставить строку ниже' }).click()
  await expect(rows).toHaveCount(4)
  await expect(rows.nth(2).locator('td').first()).toHaveText('')
  await expect(rows.nth(3).locator('td').first()).toHaveText('B')
  await rows.nth(1).locator('td').first().click()
  await page.keyboard.press('Alt+F10')
  await expect(page.getByRole('button', { name: 'Вставить строку выше' })).toBeFocused()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Вставить столбец справа' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(rows.nth(1).locator('td')).toHaveCount(3)
  await expect(rows.nth(1).locator('td').nth(1)).toHaveText('')
  await expect(rows.nth(1).locator('td').nth(2)).toHaveText('100')
  await page.getByRole('button', { name: 'Добавить строку в конец таблицы' }).click()
  await expect(rows).toHaveCount(5)

  // Drag the actual JPEGs into ordinary paragraph content. The block lands
  // above the paragraph and the inline image lands between its characters.
  const image = editor.locator('.milkdown-image-block img[alt="Схема сети"]')
  const inline = editor.locator('.milkdown-image-inline img[alt="Узлы"]')
  // Some browsers retain the native File when an image lands inside its own
  // editor. Reproduce that transfer alongside the two real mouse drags below.
  for (const picture of [image, inline]) {
    await picture.evaluate((source, encoded) => {
      const target = source.closest('.ProseMirror')!.querySelector('p')!
      const rect = target.getBoundingClientRect()
      const transfer = new DataTransfer()
      const bytes = Uint8Array.from(atob(encoded), char => char.charCodeAt(0))
      const file = new File([bytes], 'network.jpg', { type: 'image/jpeg' })
      transfer.items.add(file)
      source.dispatchEvent(new DragEvent('dragstart', { bubbles: true, cancelable: true, dataTransfer: transfer }))
      if (!transfer.files.length) transfer.items.add(file)
      target.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, clientX: rect.left + 30, clientY: rect.top + 2, dataTransfer: transfer }))
    }, jpeg)
  }
  await image.dragTo(first, { targetPosition: { x: 65, y: 2 } })
  await expect(image).toHaveCount(1)
  await expect(first.locator('xpath=preceding-sibling::*[1]')).toHaveClass(/milkdown-image-block/)
  await inline.dragTo(third, { targetPosition: { x: 30, y: 10 } })
  await expect(inline).toHaveCount(1)
  await expect(inline.locator('xpath=ancestor::p[1]')).toContainText('абзац')
  const imageSelect = page.getByRole('combobox', { name: 'Размер изображения Схема сети' })
  await image.hover()
  const fullWidth = (await image.boundingBox())!.width
  const grip = editor.locator('.milkdown-image-block .grip-right')
  const corner = (await grip.boundingBox())!
  await page.mouse.move(corner.x + corner.width / 2, corner.y + corner.height / 2)
  await page.mouse.down()
  await page.mouse.move(corner.x + corner.width / 2 - fullWidth / 4, corner.y + corner.height / 2, { steps: 8 })
  await page.mouse.up()
  await expect(imageSelect).toHaveValue('50')
  await expect.poll(async () => Math.round((await image.boundingBox())!.width / fullWidth * 100)).toBe(50)
  await imageSelect.focus()
  await imageSelect.selectOption('25')
  await expect.poll(async () => Math.round((await image.boundingBox())!.width / fullWidth * 100)).toBe(25)
  await page.getByLabel('Настройки редактора', { exact: true }).click()
  await page.getByLabel('Размер всех иллюстраций').selectOption('75')
  await page.getByRole('button', { name: 'Применить ко всем' }).click()
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Сохранено на сервере' })).toBeVisible()
  const stored = (await (await page.request.get('/api/notes/' + note.id)).json()).markdown as string
  expect(unexpectedUploads).toBe(0)
  expect(stored.split(url)).toHaveLength(3)
  expect(stored.match(/width=75%/g)).toHaveLength(2)
  expect(stored).toContain('Исходная подпись')
  expect(stored).toContain('Подпись в строке')
  expect(stored.indexOf('![Схема сети]')).toBeLessThan(stored.indexOf('Первый абзац'))
  expect(stored).toMatch(/Т[^\n]*!\[Узлы\][^\n]*абзац/)
  await image.hover()
  await expect(imageSelect).toBeVisible()
  await capture(page, 'block-editor-1440')
  await page.setViewportSize({ width: 390, height: 844 })
  await capture(page, 'block-editor-390')
  await page.getByRole('link', { name: 'Чтение' }).click()
  await page.reload()
  await expect(page.locator('.quartz-reader img[alt="Схема сети"]')).toHaveAttribute('title', 'Исходная подпись')
  await expect(page.locator('.quartz-reader img[alt="Узлы"]')).toHaveAttribute('title', 'Подпись в строке')
  await expect(page.locator('.quartz-reader img[data-image-scale="0.75"]')).toHaveCount(2)
  await expect(page.locator('.quartz-reader table tr')).toHaveCount(5)
})
