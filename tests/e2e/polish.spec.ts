  await page.getByLabel('API-ключ', { exact: true }).fill('sk-ant-test-' + 'x'.repeat(40))
  await page.getByRole('button', { name: 'Сохранить подключение', exact: true }).click()
  await expect(page.locator('.provider-row').filter({ hasText: 'Свой API' })).toContainText('Подключён')
  expect(await page.evaluate(() => Object.values(localStorage).some(value => value.includes('sk-ant-test-')))).toBe(false)
  page.once('dialog', dialog => dialog.accept())
