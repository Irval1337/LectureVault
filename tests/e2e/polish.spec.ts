import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const baseDraft = { title: 'Черновик — длинное имя исходного материала', sourceType: 'url', url: 'https://www.youtube.com/watch?v=draft', courseId: '', preset: 'seminar', length: 'detailed', instructions: 'Сохранить определения, формулы, таблицы и код.', pdfName: 'Сохранённая презентация.pdf' }
async function createInDialog(page: Page, title: string) {
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Название курса', { exact: true }).fill(title)
  await dialog.getByRole('button', { name: 'Создать курс', exact: true }).click()
  await expect(dialog).not.toBeVisible()
}

test('polish: first course returns to draft, course changes survive refresh, precise upload errors', async ({ page }) => {
  await page.addInitScript(draft => { if (!localStorage.getItem('lecturevault.draft.v1')) localStorage.setItem('lecturevault.draft.v1', JSON.stringify(draft)) }, baseDraft)
  await page.goto('/new')
  await page.locator('main').getByRole('button', { name: 'Создать курс', exact: true }).click()
  await createInDialog(page, 'Первый курс')
  await expect(page.getByRole('heading', { name: 'Новый конспект', exact: true })).toBeVisible()
  await expect(page.getByLabel('Название', { exact: true })).toHaveValue(baseDraft.title)
  await expect(page.getByLabel('Ссылка на видео')).toHaveValue(baseDraft.url)
  await expect(page.getByLabel('Инструкции к конспекту', { exact: false })).toHaveValue(baseDraft.instructions)
  await expect(page.getByRole('button', { name: 'Семинар', exact: false })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Подробно', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.locator('.field-label-row').getByRole('button', { name: 'Создать курс', exact: true }).click()
  await createInDialog(page, 'Второй курс')
  await expect(page.locator('#note-course option:checked')).toHaveText('Второй курс')
  await expect(page.getByLabel('Название', { exact: true })).toHaveValue(baseDraft.title)
  const firstCourse = await page.locator('#note-course option').first().getAttribute('value')
  await page.getByLabel('Сохранить в курс', { exact: true }).selectOption(firstCourse!)
  await page.reload()
  await expect(page.locator('#note-course option:checked')).toHaveText('Первый курс')
  await expect(page.getByLabel('Инструкции к конспекту', { exact: false })).toHaveValue(baseDraft.instructions)
  await page.getByLabel('Ссылка на видео').fill('javascript:alert(1)')
  await page.getByRole('button', { name: 'Создать конспект', exact: true }).click()
  await expect(page.locator('#source-error')).toContainText('http')
  await expect(page.getByLabel('Ссылка на видео')).toHaveAttribute('aria-describedby', /source-error/)
  await page.getByRole('tab', { name: 'Видеофайл', exact: true }).click()
  await page.locator('#video-file').setInputFiles({ name: 'wrong.txt', mimeType: 'text/plain', buffer: Buffer.from('synthetic') })
  await expect(page.locator('#source-error')).toContainText('MP4')
  await page.locator('#video-file').setInputFiles({ name: 'empty.mp4', mimeType: 'video/mp4', buffer: Buffer.alloc(0) })
  await expect(page.locator('#source-error')).toContainText('непустое видео')
  const videoName = 'Полное длинное имя видеозаписи для проверки tooltip и сохранения черновика.mp4'
  await page.locator('#video-file').setInputFiles({ name: videoName, mimeType: 'video/mp4', buffer: Buffer.alloc(2048) })
  await expect(page.locator('#source-error')).toHaveCount(0)
  await expect(page.locator('.selected-file strong')).toHaveAttribute('title', videoName)
  await page.getByLabel('PDF-презентация', { exact: true }).setInputFiles({ name: 'wrong.pdf', mimeType: 'application/pdf', buffer: Buffer.alloc(0) })
  await expect(page.locator('#pdf-error')).toContainText('50 МБ')
  await page.getByRole('tab', { name: 'Ссылка', exact: true }).click()
  await page.getByRole('tab', { name: 'Видеофайл', exact: true }).click()
  await expect(page.locator('#pdf-error')).toContainText('50 МБ')
  await page.getByRole('button', { name: 'Создать конспект', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Новый конспект', exact: true })).toBeVisible()
  await expect(page.locator('#pdf-error')).toContainText('50 МБ')
  await page.getByLabel('PDF-презентация', { exact: true }).setInputFiles({ name: 'Слайды лекции.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-synthetic') })
  await expect(page.locator('#pdf-error')).toHaveCount(0)
  await page.getByRole('tab', { name: 'Ссылка', exact: true }).click()
  await page.getByRole('tab', { name: 'Видеофайл', exact: true }).click()
  await expect(page.locator('.selected-file strong')).toHaveText(videoName)
  await expect(page.getByLabel('Название', { exact: true })).toHaveValue(baseDraft.title)
  await expect(page.getByLabel('Инструкции к конспекту', { exact: false })).toHaveValue(baseDraft.instructions)
  await page.locator('.activity-rail').getByRole('link', { name: 'Библиотека', exact: true }).click()
  await page.locator('.activity-rail').getByRole('button', { name: 'Новый конспект', exact: true }).click()
  await expect(page.getByLabel('Название', { exact: true })).toHaveValue(baseDraft.title)
  await expect(page.locator('.selected-file strong')).toHaveText(videoName)
})

test('polish: empty-library new action is actionable; rail sections and keyboard focus', async ({ page }) => {
  await page.goto('/')
  await page.locator('.activity-rail').getByRole('button', { name: 'Новый конспект', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Первый курс', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.locator('.activity-rail').getByRole('button', { name: 'Новый конспект', exact: true }).click()
  await createInDialog(page, 'Курс для навигации')
  await expect(page.locator('.activity-rail').getByRole('button', { name: 'Новый конспект', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.desktop-sidebar .main-nav')).not.toBeVisible()
  await page.getByRole('button', { name: 'Скрыть проводник', exact: true }).focus()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: 'Скрыть проводник', exact: true })).toBeFocused()
  expect(await page.getByRole('button', { name: 'Скрыть проводник', exact: true }).evaluate(el => getComputedStyle(el).outlineStyle)).not.toBe('none')
  await page.keyboard.press('Space')
  await expect(page.locator('.desktop-sidebar')).not.toBeVisible()
  await page.keyboard.press('Control+k')
  await expect(page.getByLabel('Поиск по библиотеке')).toBeFocused()
  await page.locator('.activity-rail').getByRole('link', { name: 'Очередь заданий', exact: true }).click()
  await expect(page.locator('.activity-rail').getByRole('link', { name: 'Очередь заданий', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Открыть навигацию', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Новый конспект', exact: true })).toBeVisible()
  await page.getByRole('dialog').getByRole('link', { name: 'Библиотека', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.getByRole('heading', { name: 'Библиотека', exact: true })).toBeVisible()
})

test('polish: real horizontal scroll, math/code/image bounds, TOC/menu/back at 1440/768/390', async ({ page }) => {
  const markdown = '# Широкие материалы\n\n## Таблицы\n\n| A | B | C |\n| - | - | - |\n| ' + 'long_column_'.repeat(40) + ' | Данные | Пример |\n\n| A | B |\n| - | - |\n| 1 | 2 |\n\n## Код\n\n```text\n' + 'long_command_'.repeat(70) + '\n```\n\n## Формулы\n\n$$\n\\text{' + 'WideTerm'.repeat(70) + '}\n$$\n\nInline: $\\text{' + 'InlineTerm'.repeat(50) + '}$\n\n## Изображение\n\n![Материал](/demo-replication.svg)'
  await page.addInitScript(markdown => {
    if (!localStorage.getItem('lecturevault.library.v1')) localStorage.setItem('lecturevault.library.v1', JSON.stringify({ version: 1, courses: [{ id: 'wide-course', title: 'Курс широких материалов', workspace: 'personal', createdAt: 1794348000000 }], notes: [{ id: 'wide-note', courseId: 'wide-course', title: 'Широкие материалы', markdown, createdAt: 1794348000000, jobId: 'none' }], jobs: [], expandedCourses: ['wide-course'], readerTheme: 'dark' }))
  }, markdown)
  await page.goto('/notes/wide-note')
  await page.locator('.table-container').first().waitFor()
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 })
    const wide = page.locator('.table-container').first()
    await expect(wide).toHaveAttribute('data-horizontal-scroll', '')
    await expect(page.locator('.table-container').nth(1)).not.toHaveAttribute('data-horizontal-scroll')
    for (const selector of ['.table-container', 'pre > code', '.katex-display', 'p > .katex']) {
      const block = page.locator(`.quartz-reader ${selector}`).first()
      await expect(block).toHaveAttribute('data-horizontal-scroll', '')
      await block.evaluate(el => { el.scrollLeft = 0 })
      await block.focus()
      await page.keyboard.press('ArrowRight')
      await expect.poll(() => block.evaluate(el => el.scrollLeft)).toBeGreaterThan(0)
      await expect(block).toHaveAttribute('data-scroll-hint', /←/)
      await block.evaluate(el => { el.scrollLeft = el.scrollWidth })
      await expect.poll(() => block.getAttribute('data-scroll-hint')).not.toContain('→')
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    const image = page.locator('.quartz-reader img')
    await expect.poll(() => image.evaluate((el: HTMLImageElement) => el.naturalWidth)).toBeGreaterThan(0)
    expect(await image.evaluate(el => el.getBoundingClientRect().width)).toBeLessThanOrEqual(width)
    if (width === 768) {
      const navBounds = await page.locator('.desktop-sidebar').boundingBox()
      const treeBounds = await page.locator('.desktop-sidebar .explorer').boundingBox()
      expect(treeBounds!.x).toBeGreaterThanOrEqual(navBounds!.x)
      expect(treeBounds!.x + treeBounds!.width).toBeLessThanOrEqual(navBounds!.x + navBounds!.width)
    }
    if (width < 1180) {
      await page.getByRole('button', { name: 'Оглавление', exact: true }).click()
      const beforeScroll = await page.evaluate(() => scrollY)
      await page.locator('.mobile-toc').getByRole('link', { name: 'Изображение', exact: true }).click()
      await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(beforeScroll)
      await expect(page.locator('.mobile-toc > button')).toHaveAttribute('aria-expanded', 'false')
      await expect.poll(() => page.locator('#section-изображение').evaluate(el => Math.round(el.getBoundingClientRect().top))).toBeLessThan(width === 390 ? 814 : 970)
      await expect.poll(() => page.evaluate(() => decodeURIComponent(location.hash))).toBe('#section-изображение')
    }
  }
  await page.getByRole('button', { name: 'Открыть навигацию', exact: true }).click()
  await expect(page.getByRole('dialog').locator('.tree-children a.active')).toHaveText('Широкие материалы')
  await page.keyboard.press('Escape')
  await page.getByRole('link', { name: 'К курсу', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Курс широких материалов' })).toBeVisible()
  expect(errors).toEqual([])
})
