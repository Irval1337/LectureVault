import { test, expect } from '@playwright/test'
const headers = { 'X-LectureVault': '1' }

test('draft survives validation and refresh; connection dialog contains no device-code or model controls', async ({ page }) => {
  await page.request.post('/api/auth/login', { headers, data: { userId: 'bob' } })
  const cid = (await (await page.request.post('/api/courses', { headers, data: { title: `Черновики ${Date.now()}` } })).json()).id
  await page.goto(`/new?course=${cid}`)
  await page.getByLabel('Название', { exact: true }).fill('Мой черновик')
  await page.getByLabel('Инструкции к конспекту', { exact: false }).fill('Сохранить таблицы и определения.')
  await page.getByRole('button', { name: 'Подробно', exact: true }).click()
  await page.locator('#video-file').setInputFiles({ name: 'wrong.txt', mimeType: 'text/plain', buffer: Buffer.from('invalid') })
  await expect(page.locator('#source-error')).toContainText('MP4')
  await page.getByRole('button', { name: 'Создать конспект', exact: true }).click()
  await expect(page.locator('#source-error')).toBeVisible()
  await expect(page.getByLabel('Название', { exact: true })).toHaveValue('Мой черновик')
  await page.reload()
  await expect(page.getByLabel('Инструкции к конспекту', { exact: false })).toHaveValue('Сохранить таблицы и определения.')
  await expect(page.getByRole('button', { name: 'Подробно', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.locator('.desktop-sidebar .account-trigger').click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('heading', { name: 'Подключения', exact: true })).toBeVisible()
  await expect(dialog).toContainText('Codex'); await expect(dialog).toContainText('Claude')
  await expect(dialog.getByRole('combobox')).toHaveCount(0)
  await expect(dialog.locator('.device-code')).toHaveCount(0)
  await page.keyboard.press('Escape'); await expect(dialog).not.toBeVisible()
})

test('two users: shared editor, viewer permissions and revision conflict preserve local draft', async ({ browser }) => {
  const contextA = await browser.newContext(); const contextB = await browser.newContext()
  const a = await contextA.newPage(); const b = await contextB.newPage()
  await a.request.post('/api/auth/login', { headers, data: { userId: 'alice' } })
  await b.request.post('/api/auth/login', { headers, data: { userId: 'bob' } })
  const cid = (await (await a.request.post('/api/courses', { headers, data: { title: `Общий ${Date.now()}`, workspace: 'shared' } })).json()).id
  const note = (await (await a.request.post('/api/notes', { headers, data: { courseId: cid, title: 'Общая заметка', markdown: '## Начало\n\nИсходный текст' } })).json())
  await b.goto(`/notes/${note.id}/edit`)
  await expect(b.locator('.milkdown .ProseMirror')).toBeVisible()
  await b.getByLabel('Название заметки', { exact: true }).fill('Локальный черновик Марии')
  await a.request.patch(`/api/notes/${note.id}`, { headers, data: { title: 'Изменение Алексея', markdown: '## Обновлено\n\nСохранённый текст', revision: 1 } })
  await b.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(b.getByRole('alert')).toContainText('уже изменён')
  await expect(b.getByLabel('Название заметки', { exact: true })).toHaveValue('Локальный черновик Марии')
  const download = b.waitForEvent('download')
  await b.getByRole('button', { name: 'Скачать черновик', exact: true }).click()
  expect((await download).suggestedFilename()).toContain('Локальный черновик Марии')
  b.once('dialog', dialog => dialog.accept())
  await b.getByRole('button', { name: 'Загрузить актуальную версию', exact: true }).click()
  await expect(b.getByLabel('Название заметки', { exact: true })).toHaveValue('Изменение Алексея')
  await a.request.put(`/api/courses/${cid}/members/bob`, { headers, data: { role: 'viewer' } })
  await b.goto(`/notes/${note.id}`)
  await expect(b.getByRole('button', { name: 'Редактировать', exact: true })).toHaveCount(0)
  expect((await b.request.patch(`/api/notes/${note.id}`, { headers, data: { title: 'Denied', markdown: '', revision: 2 } })).status()).toBe(403)
  await b.goto(`/new?course=${cid}`)
  await expect(b.locator(`#note-course option[value="${cid}"]`)).toHaveCount(0)
  await a.goto(`/courses/${cid}`)
  await a.getByRole('button', { name: 'Доступ', exact: true }).click()
  await expect(a.getByRole('dialog')).toContainText('Мария')
  await contextA.close(); await contextB.close()
})

