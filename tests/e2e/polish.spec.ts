import { test, expect, headers, signIn, createCourse, capture } from './fixtures'

test('real users: owner adds by email, viewer is read-only, editor conflicts preserve drafts, revocation works', async ({ browser, accounts }) => {
  const aContext = await browser.newContext({ baseURL: process.env.TEST_BASE_URL })
  const bContext = await browser.newContext({ baseURL: process.env.TEST_BASE_URL })
  const a = await aContext.newPage(); const b = await bContext.newPage()
  await signIn(a, accounts.author); await signIn(b, accounts.reader)
  const cid = await createCourse(a.request, `Совместная категория ${Date.now()}`, 'shared')
  const note = await (await a.request.post('/api/notes', { headers, data: { courseId: cid, title: 'Общая заметка', markdown: '## Начало\n\nИсходный текст.' } })).json()
  expect((await b.request.get(`/api/notes/${note.id}`)).status()).toBe(404)
  await a.goto(`/courses/${cid}`); await a.getByRole('button', { name: 'Доступ', exact: true }).click()
  await a.getByText('Добавить по email', {exact: true}).click()
  await a.getByLabel('Добавить участника по email').fill(accounts.reader.email)
  await a.getByRole('button', { name: 'Добавить участника', exact: true }).click()
  await expect(a.getByRole('dialog').getByText(accounts.reader.email, { exact: true })).toBeVisible()
  await b.goto(`/notes/${note.id}`); await expect(b.locator('.quartz-reader article')).toBeVisible()
  await expect(b.getByRole('button', { name: 'Редактировать', exact: true })).toHaveCount(0)
  expect((await b.request.patch(`/api/notes/${note.id}`, { headers, data: { title: 'Denied', markdown: '', revision: 1 } })).status()).toBe(403)
  await a.getByLabel('Роль Участник', { exact: true }).selectOption('editor')
  await expect.poll(async () => (await (await a.request.get(`/api/courses/${cid}/members`)).json()).find((m: { id: string }) => m.id === accounts.reader.id).role).toBe('editor')
  await b.reload(); await b.getByRole('button', { name: 'Редактировать', exact: true }).click()
  await expect(b.locator('.milkdown .ProseMirror')).toBeVisible()
  await b.getByLabel('Название заметки', { exact: true }).fill('Мой несохранённый черновик')
  await a.request.patch(`/api/notes/${note.id}`, { headers, data: { title: 'Правка владельца', markdown: '## Обновлено\n\nСохранённый текст.', revision: 1 } })
  await b.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(b.getByRole('alert')).toContainText('уже изменён')
  await expect(b.getByLabel('Название заметки', { exact: true })).toHaveValue('Мой несохранённый черновик')
  const download = b.waitForEvent('download')
  await b.getByRole('button', { name: 'Скачать черновик', exact: true }).click()
  expect((await download).suggestedFilename()).toContain('Мой несохранённый черновик')
  b.once('dialog', dialog => dialog.accept())
  await b.getByRole('button', { name: 'Загрузить актуальную версию', exact: true }).click()
  await expect(b.getByLabel('Название заметки', { exact: true })).toHaveValue('Правка владельца')
  a.once('dialog', dialog => dialog.accept())
  await a.getByLabel('Роль Участник', { exact: true }).selectOption('none')
  await expect(a.getByRole('dialog').getByText(accounts.reader.email, { exact: true })).toHaveCount(0)
  expect((await b.request.get(`/api/notes/${note.id}`)).status()).toBe(404)
  await aContext.close(); await bContext.close()
})

