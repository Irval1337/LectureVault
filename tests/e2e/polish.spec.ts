test('persistent queue: several jobs, cancel, error/retry and leaving the page (isolated test adapter only)', async ({ page, accounts }) => {
  await signIn(page, accounts.author)
  const cid = await createCourse(page.request, `Очередь ${Date.now()}`)
  const ids: string[] = []
  for (let i = 0; i < 4; i++) {
    const response = await page.request.post('/api/jobs', { headers, multipart: { metadata: JSON.stringify({ courseId: cid, title: `Проверка очереди ${i}`, sourceType: 'url', sourceName: i === 2 ? 'https://error.example/lecture' : 'https://example.com/no-network', mode: 'mock' }) } })
    expect(response.status()).toBe(201); ids.push((await response.json()).id)
  }
  await page.goto(`/queue?job=${ids[3]}`)
  const cancelled = page.locator('.job-item').filter({ hasText: 'Проверка очереди 3' })
  await cancelled.getByRole('button', { name: 'Отменить', exact: true }).click()
  await expect(cancelled).toContainText('Отменено')
  const firstTitle = page.getByRole('button',{name:'Проверка очереди 0',exact:true})
  if (await firstTitle.getAttribute('aria-expanded') === 'true') await firstTitle.click()
  await firstTitle.click()
  await expect(page.locator('#stages-' + ids[0])).toBeVisible()
  await expect(page.locator('#stages-' + ids[3])).toBeVisible()
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: width === 1440 ? 1000 : 844 }); await capture(page, `queue-test-adapter-${width}`)
  }
  await page.goto('/'); await page.goto(`/queue?job=${ids[2]}`); await page.reload()
  const failed = page.locator('.job-item').filter({ hasText: 'Проверка очереди 2' })
  await failed.getByRole('button', { name: 'Повторить', exact: true }).click()
  await failed.getByRole('link', { name: 'Открыть', exact: true }).click()
  await expect(page.locator('.quartz-reader article')).toBeVisible()
  const state = await (await page.request.get('/api/state')).json()
  expect(state.jobs.find((job: { id: string }) => job.id === ids[2]).attempt).toBe(1)
  expect(state.notes.filter((note: { courseId: string }) => note.courseId === cid)).toHaveLength(3)
})
