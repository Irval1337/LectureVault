import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const SHOTS = 'test-results/screenshots/flows/'
const APP_ORIGIN = new URL(process.env.TEST_BASE_URL ?? 'http://127.0.0.1:4173').origin
async function createCourse(page: Page, title = 'Распределённые системы') {
  await page.locator('.library-empty').getByRole('button', { name: 'Создать курс', exact: true }).click()
  await page.getByLabel('Название курса', { exact: true }).fill(title)
  await page.getByRole('button', { name: 'Создать курс', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name: title })).toBeVisible()
}
async function newUrlJob(page: Page, title: string, url = 'https://www.youtube.com/watch?v=demo') {
  await page.locator('.activity-rail').getByRole('button', { name: 'Новый конспект', exact: true }).click()
  await page.getByRole('tab', { name: 'Ссылка', exact: true }).click()
  await page.getByLabel('Ссылка на видео').fill(url)
  await page.getByLabel('Название', { exact: true }).fill(title)
  await page.getByRole('button', { name: 'Создать конспект', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Очередь заданий', exact: true })).toBeVisible()
}
async function noOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
}
async function screenshot(page: Page, name: string, fullPage = true) {
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await page.screenshot({ path: SHOTS + name, fullPage })
}

