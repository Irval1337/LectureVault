test('password recovery is delivered by SMTP and a new user can sign in and delete the account', async ({ page }) => {
  const account = await createAccount(page.request, 'Восстановление')
  await page.request.post('/api/auth/logout', { headers })
  await page.goto('/forgot-password'); await page.getByLabel('Email', { exact: true }).fill(account.email)
  await page.getByRole('button', { name: 'Отправить ссылку', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('письмо')
  await page.goto(await emailLink(page.request, account.email, '/reset-password'))
  const nextPassword = 'A different secure recovery password'
  await page.getByLabel('Пароль', { exact: true }).fill(nextPassword)
  await page.getByLabel('Повторите пароль').fill(nextPassword)
  await page.getByRole('button', { name: 'Сохранить пароль', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Пароль изменён')
  await page.getByRole('link', { name: 'Ко входу', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(account.email)
  await page.getByLabel('Пароль', { exact: true }).fill(nextPassword)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Библиотека', exact: true })).toBeVisible()
  await page.goto('/settings')
  await page.locator('.account-removal summary').click()
  await page.getByLabel('Пароль для подтверждения', { exact: true }).fill(nextPassword)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Удалить аккаунт и данные', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Вход', exact: true })).toBeVisible()
  expect((await page.request.post('/api/auth/login', { headers, data: { email: account.email, password: nextPassword } })).status()).toBe(401)
})
