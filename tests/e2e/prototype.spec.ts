test('URL validation, draft persistence, queued cancellation and demonstrative error retry', async ({ page }) => {
  await page.goto('/')
  await createCourse(page, 'АКОС')
  await page.locator('main').getByRole('button', { name: 'Новый конспект', exact: true }).click()
  await page.getByRole('tab', { name: 'Ссылка', exact: true }).click()
  await page.getByLabel('Название', { exact: true }).fill('Тестовая лекция')
  await page.getByLabel('Ссылка на видео').fill('javascript:alert(1)')
  await page.getByRole('button', { name: 'Создать конспект', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('http')
  await expect(page.getByLabel('Название', { exact: true })).toHaveValue('Тестовая лекция')
  await page.getByLabel('Ссылка на видео').fill('https://www.youtube.com/watch?v=demo')
  await page.reload()
  await expect(page.getByLabel('Название', { exact: true })).toHaveValue('Тестовая лекция')
  await expect(page.getByLabel('Ссылка на видео')).toHaveValue('https://www.youtube.com/watch?v=demo')
  await page.getByRole('button', { name: 'Создать конспект', exact: true }).click()
  await newUrlJob(page, 'Ожидающая лекция')
  await page.getByRole('button', { name: 'Отменить', exact: true }).click()
  await expect(page.locator('.job-item').filter({ hasText: 'Ожидающая лекция' })).toContainText('Отменено')
  await page.getByRole('tab', { name: 'В работе' }).click()
  await expect(page.locator('.job-item')).toHaveCount(1)
  await page.getByRole('tab', { name: 'Все', exact: false }).click()
  await expect(page.locator('.job-item')).toHaveCount(2)
  await expect(page.getByRole('link', { name: 'Открыть', exact: true })).toBeVisible()
  await newUrlJob(page, 'Проверка ошибки', 'https://error.example/lecture')
  await expect(page.getByRole('button', { name: 'Повторить', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Повторить', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Открыть', exact: true })).toHaveCount(2)
  await page.reload()
  await expect(page.locator('.job-item')).toHaveCount(3)
})

