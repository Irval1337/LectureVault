import { test, expect, signIn } from './fixtures'

test('settings sections have direct links, preserve input and keep provider credentials out of the overview', async ({ page, accounts }) => {
  await signIn(page, accounts.author)
  await page.goto('/settings')
  await expect(page.getByRole('tab', { name: 'Профиль', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByLabel('Имя', { exact: true }).fill('Несохранённое имя')
  await page.getByRole('tab', { name: 'Подключения', exact: true }).click()
  await expect(page).toHaveURL(/#connections$/)
  await expect(page.locator('.provider-row').filter({ hasText: 'Codex' })).toBeVisible()
  await expect(page.getByLabel('Ключ Anthropic API', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Подключить Claude', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByLabel('Ключ Anthropic API', { exact: true }).fill('sk-ant-unsaved-private-value')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Подключить Claude', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Подключить Claude', exact: true }).click()
  await expect(page.getByLabel('Ключ Anthropic API', { exact: true })).toHaveValue('')
  await page.keyboard.press('Escape')
  await page.getByRole('tab', { name: 'Профиль', exact: true }).click()
  await expect(page.getByLabel('Имя', { exact: true })).toHaveValue('Несохранённое имя')
  await page.goto('/settings#security')
  await expect(page.getByRole('tab', { name: 'Безопасность', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByLabel('Текущий пароль', { exact: true }).fill('Not submitted in this check')
  await page.getByLabel('Новый пароль', { exact: true }).fill('A long new password for this check')
  await page.getByLabel('Повторите новый пароль', { exact: true }).fill('A different password for this check')
  const writes: string[] = []
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/api/auth/change-password')) writes.push(request.url()) })
  await page.getByRole('button', { name: 'Изменить пароль', exact: true }).click()
  await expect(page.locator('.settings-password-form').getByRole('alert')).toContainText('не совпадают')
  expect(writes).toEqual([])
})

test('OpenAI API connection from a video draft preserves attachments and submits the chosen settings', async ({ page, accounts }) => {
  await signIn(page, accounts.author)
  const course = await page.request.post('/api/courses', { headers: { 'X-LectureVault': '1' }, data: { title: 'API ' + Date.now() } })
  expect(course.status()).toBe(201)
  const cid = (await course.json()).id
  await page.goto('/new?course=' + cid)
  await page.getByLabel('Провайдер', { exact: true }).selectOption('openai')
  await page.getByLabel('Модель', { exact: true }).selectOption('gpt-6.1-sol')
  await page.getByLabel('Effort', { exact: true }).selectOption('high')
  // Header is recognized on upload, but cannot be decoded. No transcript or paid request can be produced.
  await page.locator('#video-file').setInputFiles({ name: 'Нечитаемая запись.mp4', mimeType: 'video/mp4', buffer: Buffer.from('0000ftypmp42') })
  const pdf = page.getByLabel('PDF-презентация', { exact: true })
  await pdf.setInputFiles({ name: 'Слайды.txt', mimeType: 'text/plain', buffer: Buffer.from('Not a PDF') })
  await page.getByRole('button', { name: 'Продолжить без PDF' }).click()
  await expect(page.locator('#pdf-error')).toHaveCount(0)
  await pdf.setInputFiles({ name: 'Слайды.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4 test') })
  await page.getByRole('link', { name: 'Подключить в настройках' }).click()
  await page.getByRole('button', { name: 'Подключить OpenAI API', exact: true }).click()
  const key = 'sk-proj-browser-test-' + 'x'.repeat(24)
  await page.getByLabel('Ключ OpenAI API', { exact: true }).fill(key)
  await page.getByRole('button', { name: 'Сохранить ключ' }).click()
  const row = page.locator('.provider-row').filter({ hasText: 'OpenAI API' })
  await expect(row).toContainText('Ключ сохранён')
  expect(await (await page.request.get('/api/providers')).text()).not.toContain(key)
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain(key)
  // Another tab may have written a different draft to the shared browser store.
  await page.evaluate(user => {
    const key = 'lecturevault.generation-draft.' + user
    localStorage.setItem(key, JSON.stringify({ ...JSON.parse(localStorage.getItem(key)!), title: 'Другая запись', file: { name: 'other.mp4', size: 42 }, pdfName: 'other.pdf' }))
  }, accounts.author.id)
  await page.getByRole('link', { name: 'Вернуться к конспекту' }).click()
  await expect(page.getByLabel('Название', { exact: true })).toHaveValue('Нечитаемая запись')
  await expect(page.locator('.selected-file')).toContainText('Нечитаемая запись.mp4')
  await expect(page.locator('.selected-file')).toContainText('видео выбрано')
  await expect(page.locator('.pdf-chip')).toContainText('Слайды.pdf')
  await expect(page.getByLabel('Модель', { exact: true })).toHaveValue('gpt-6.1-sol')
  await expect(page.getByLabel('Effort', { exact: true })).toHaveValue('high')
  let releaseUpload!: () => void
  const pendingUpload = new Promise<void>(resolve => { releaseUpload = resolve })
  let requests = 0
  await page.route('**/api/jobs', async route => {
    requests++; await pendingUpload; await route.continue()
  })
  await page.getByRole('button', { name: 'Создать конспект', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Загружаем' })).toBeVisible()
  await page.locator('.activity-rail').getByRole('link', { name: 'Библиотека', exact: true }).click()
  await page.goBack()
  await expect(page.getByRole('status').filter({ hasText: 'Загружаем' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Создать конспект', exact: true })).toHaveCount(0)
  releaseUpload()
  await expect(page).toHaveURL(/\/queue\?job=/)
  expect(requests).toBe(1)
  const id = new URL(page.url()).searchParams.get('job')
  const job = page.locator('.job-item').filter({ hasText: 'Нечитаемая запись' })
  await expect(job).toContainText('Whisper + OpenAI API')
  await expect(job.getByRole('button', { name: 'Повторить' })).toBeVisible()
  const saved = await (await page.request.get('/api/jobs/' + id)).json()
  expect(saved).toMatchObject({ provider: 'openai', model: 'gpt-6.1-sol', effort: 'high', pdfName: 'Слайды.pdf', mode: 'real', courseId: cid, status: 'failed' })
  await page.goto('/settings#connections')
  page.once('dialog', dialog => dialog.accept())
  await row.getByRole('button', { name: 'Отключить' }).click()
  await expect(row).toContainText('Не подключён')
})
