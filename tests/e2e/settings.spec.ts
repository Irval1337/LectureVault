import { test, expect, signIn } from './fixtures'

test('settings sections have direct links, preserve input and keep provider credentials out of the overview', async ({ page, accounts }) => {
  await signIn(page, accounts.author)
  await page.goto('/settings')
  await expect(page.getByRole('tab', { name: 'Профиль', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByLabel('Имя', { exact: true }).fill('Несохранённое имя')
  await page.getByRole('tab', { name: 'Подключения', exact: true }).click()
  await expect(page).toHaveURL(/#connections$/)
  await expect(page.locator('.provider-row').filter({ hasText: 'Codex' })).toBeVisible()
  await expect(page.getByLabel('Ключ Anthropic API', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Подключить Claude', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByLabel('Ключ Anthropic API', { exact: true }).fill('sk-ant-unsaved-private-value')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Подключить Claude', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Подключить Claude', exact: true }).click()
  await expect(page.getByLabel('Ключ Anthropic API', { exact: true })).toHaveValue('')
  await page.keyboard.press('Escape')
  await page.getByRole('tab', { name: 'Профиль', exact: true }).click()
  await expect(page.getByLabel('Имя', { exact: true })).toHaveValue('Несохранённое имя')
  await page.goto('/settings#security')
  await expect(page.getByRole('tab', { name: 'Безопасность', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByLabel('Текущий пароль', { exact: true }).fill('Not submitted in this check')
  await page.getByLabel('Новый пароль', { exact: true }).fill('A long new password for this check')
  await page.getByLabel('Повторите новый пароль', { exact: true }).fill('A different password for this check')
  const writes: string[] = []
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/api/auth/change-password')) writes.push(request.url()) })
  await page.getByRole('button', { name: 'Изменить пароль', exact: true }).click()
  await expect(page.locator('.settings-password-form').getByRole('alert')).toContainText('не совпадают')
  expect(writes).toEqual([])
})
