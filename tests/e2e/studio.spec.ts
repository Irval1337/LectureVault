import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const SHOTS = 'test-results/screenshots/studio/'
const ORIGIN = new URL(process.env.TEST_BASE_URL ?? 'http://127.0.0.1:4173').origin
const title = 'Сохранённый конспект'
async function capture(page: Page, filename: string) {
  await page.evaluate(() => document.fonts.ready)
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `${SHOTS}${filename}.png`, animations: 'disabled' })
}

test('Studio: legacy v1 data, draft, keyboard navigation and reader controls remain intact', async ({ page }) => {
  const markdown = await readFile('fixtures/workspace-reader.md', 'utf8')
  const createdAt = Date.parse('2026-11-10T10:00:00+03:00')
  const seed = {
    version: 1,
    courses: [{ id: 'old-course', title: 'Сохранённый курс', workspace: 'personal', createdAt }],
    notes: [{ id: 'persisted-note', courseId: 'old-course', title, markdown, createdAt, jobId: 'old-job' }],
    jobs: [{ id: 'old-job', courseId: 'old-course', title, sourceType: 'file', sourceName: 'Сохранённое видео.mp4', preset: 'lecture', length: 'detailed', instructions: 'Сохранить формулы', pdfName: 'Сохранённые слайды.pdf', timestamps: false, status: 'ready', createdAt, completedAt: createdAt, attempt: 0, noteId: 'persisted-note' }],
    expandedCourses: ['old-course'], readerTheme: 'light',
  }
  const draft = { courseId: 'old-course', title: 'Сохранённый черновик', sourceType: 'url', url: 'https://www.youtube.com/watch?v=saved', preset: 'seminar', length: 'short', instructions: 'Сохранённые инструкции', pdfName: 'Черновик.pdf' }
  await page.addInitScript(({ seed, draft }) => {
    if (!localStorage.getItem('lecturevault.library.v1')) {
      localStorage.setItem('lecturevault.library.v1', JSON.stringify(seed))
      localStorage.setItem('lecturevault.draft.v1', JSON.stringify(draft))
      localStorage.setItem('lecturevault.space', 'personal')
    }
  }, { seed, draft })
  await page.goto('/notes/persisted-note')
  await expect(page.getByRole('heading', { level: 1, name: title })).toBeVisible()
  await expect(page.locator('main')).toHaveClass(/reader-light/)
  const before = await page.evaluate(() => localStorage.getItem('lecturevault.library.v1'))
  await page.reload()
  await expect(page.getByRole('heading', { level: 1, name: title })).toBeVisible()
  await expect(page.locator('.quartz-reader article')).toHaveCSS('font-family', /Source Serif 4/)
  await expect(page.locator('.quartz-reader article')).toHaveCSS('font-size', '17px')
  await page.getByRole('button', { name: 'Скрыть проводник', exact: true }).click()
  await expect(page.locator('.desktop-sidebar')).not.toBeVisible()
  await page.keyboard.press('Control+k')
  await expect(page.getByLabel('Поиск по библиотеке')).toBeFocused()
  await expect(page.locator('.desktop-sidebar')).toBeVisible()
  await page.getByRole('button', { name: 'Скрыть контекст', exact: true }).click()
  await expect(page.locator('.context-sidebar')).toHaveCount(0)
  await page.getByRole('button', { name: 'Показать контекст', exact: true }).click()
  await page.getByRole('tab', { name: 'Источник', exact: true }).click()
  await expect(page.locator('.context-sidebar')).toContainText('Сохранённые слайды.pdf')
  await page.getByRole('tab', { name: 'Источник', exact: true }).press('ArrowLeft')
  await expect(page.getByRole('tab', { name: 'Оглавление', exact: true })).toHaveAttribute('aria-selected', 'true')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать .md', exact: true }).click()
  expect(await readFile((await (await downloadPromise).path())!, 'utf8')).toBe(markdown)
  await page.getByRole('button', { name: 'Тёмная тема ридера', exact: true }).click()
  await page.getByRole('button', { name: 'Светлая тема ридера', exact: true }).click()
  await page.locator('.desktop-sidebar').getByRole('link', { name: 'Демонстрационная библиотека', exact: true }).click()
  await page.locator('.note-list-row').filter({ hasText: 'Репликация и консистентность' }).click()
  await page.getByRole('button', { name: 'Светлая тема ридера', exact: true }).click()
  await page.getByRole('link', { name: 'Выйти из примера', exact: true }).click()
  await page.goto('/new?course=old-course')
  await expect(page.getByLabel('Название', { exact: true })).toHaveValue(draft.title)
  await expect(page.getByLabel('Ссылка на видео')).toHaveValue(draft.url)
  await expect(page.getByRole('button', { name: 'Семинар', exact: false })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Кратко', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByLabel('Инструкции к конспекту', { exact: false })).toHaveValue(draft.instructions)
  await page.getByRole('tab', { name: 'Ссылка', exact: true }).press('Home')
  await expect(page.getByRole('tab', { name: 'Видеофайл', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('tab', { name: 'Видеофайл', exact: true }).press('End')
  await expect(page.getByRole('tab', { name: 'Ссылка', exact: true })).toHaveAttribute('aria-selected', 'true')
  expect(await page.evaluate(() => localStorage.getItem('lecturevault.library.v1'))).toBe(before)
  expect(await page.evaluate(() => localStorage.getItem('lecturevault.space'))).toBe('personal')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('lecturevault.draft.v1')!))).toMatchObject(draft)
})

